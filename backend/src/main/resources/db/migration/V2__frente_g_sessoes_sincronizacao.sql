-- ---------------------------------------------------------------------------------------------------------------------
-- RN57 — uma sessão por token JWT (jti). Encerrada no logout, na renovação, na inativação do usuário ou por expiração
-- (rotina SessionExpirationJob, que audita SESSION_EXPIRED). Token de sessão encerrada é recusado.
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_user_sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    jti         VARCHAR(64)  NOT NULL,
    username    VARCHAR(50)  NOT NULL,
    issued_at   TIMESTAMP(6) NOT NULL,
    expires_at  TIMESTAMP(6) NOT NULL,
    ended_at    TIMESTAMP(6),
    end_reason  VARCHAR(20),
    CONSTRAINT pk_user_sessions PRIMARY KEY (id),
    CONSTRAINT uk_user_sessions_jti UNIQUE (jti),
    CONSTRAINT ck_user_sessions_end_reason CHECK (end_reason IS NULL
        OR end_reason IN ('LOGOUT', 'RENOVADA', 'EXPIRADA', 'REVOGADA')),
    CONSTRAINT ck_user_sessions_ended CHECK ((ended_at IS NULL) = (end_reason IS NULL))
);
COMMENT ON TABLE tb_user_sessions IS 'Sessões (tokens JWT) — RN57. Sessão encerrada = token recusado.';
CREATE INDEX idx_user_session_username ON tb_user_sessions (username);
CREATE INDEX idx_user_session_open ON tb_user_sessions (ended_at, expires_at);

-- ---------------------------------------------------------------------------------------------------------------------
-- RN60 — operações feitas offline e recebidas na sincronização; conflitos para conferência manual
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_sync_conflicts (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    equipment_id          BIGINT,
    existing_loan_id      BIGINT,
    client_operation_id   VARCHAR(64)   NOT NULL,
    operation_type        VARCHAR(20)   NOT NULL,
    incoming_occurred_at  TIMESTAMP(6)  NOT NULL,
    existing_occurred_at  TIMESTAMP(6),
    prevailing            VARCHAR(20)   NOT NULL,
    description           VARCHAR(1000) NOT NULL,
    status                VARCHAR(20)   NOT NULL,
    username              VARCHAR(50)   NOT NULL,
    resolution_note       VARCHAR(1000),
    resolved_by           VARCHAR(50),
    resolved_at           TIMESTAMP(6),
    created_at            TIMESTAMP(6)  NOT NULL,
    CONSTRAINT pk_sync_conflicts PRIMARY KEY (id),
    CONSTRAINT fk_sync_conflicts_equipment FOREIGN KEY (equipment_id) REFERENCES tb_equipments (id),
    CONSTRAINT fk_sync_conflicts_loan FOREIGN KEY (existing_loan_id) REFERENCES tb_loans (id),
    CONSTRAINT ck_sync_conflicts_type CHECK (operation_type IN ('RETIRADA', 'DEVOLUCAO', 'RENOVACAO')),
    CONSTRAINT ck_sync_conflicts_prevailing CHECK (prevailing IN ('EXISTENTE', 'RECEBIDA')),
    CONSTRAINT ck_sync_conflicts_status CHECK (status IN ('PENDENTE', 'RESOLVIDO')),
    CONSTRAINT ck_sync_conflicts_resolution CHECK (status <> 'RESOLVIDO' OR resolution_note IS NOT NULL)
);
COMMENT ON TABLE tb_sync_conflicts IS 'Conflitos de sincronização (RN60): prevalece a data/hora mais antiga; conferência manual.';
CREATE INDEX idx_sync_conflict_status ON tb_sync_conflicts (status);

CREATE TABLE tb_sync_operations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    client_operation_id  VARCHAR(64)   NOT NULL,
    type                 VARCHAR(20)   NOT NULL,
    beneficiary_id       BIGINT,
    equipment_id         BIGINT,
    loan_id              BIGINT,
    occurred_at          TIMESTAMP(6)  NOT NULL,
    received_at          TIMESTAMP(6)  NOT NULL,
    username             VARCHAR(50)   NOT NULL,
    result               VARCHAR(20)   NOT NULL,
    message              VARCHAR(1000),
    resulting_loan_id    BIGINT,
    conflict_id          BIGINT,
    CONSTRAINT pk_sync_operations PRIMARY KEY (id),
    CONSTRAINT uk_sync_operations_client_id UNIQUE (client_operation_id),
    CONSTRAINT fk_sync_operations_resulting_loan FOREIGN KEY (resulting_loan_id) REFERENCES tb_loans (id),
    CONSTRAINT fk_sync_operations_conflict FOREIGN KEY (conflict_id) REFERENCES tb_sync_conflicts (id),
    CONSTRAINT ck_sync_operations_type CHECK (type IN ('RETIRADA', 'DEVOLUCAO', 'RENOVACAO')),
    CONSTRAINT ck_sync_operations_result CHECK (result IN ('APLICADA', 'RECUSADA', 'CONFLITO', 'DUPLICADA'))
);
COMMENT ON TABLE tb_sync_operations IS 'Operações offline recebidas (RN60). client_operation_id garante idempotência; '
    'beneficiary_id/equipment_id/loan_id guardam o que o dispositivo enviou (sem FK: podem não existir).';
CREATE INDEX idx_sync_operation_loan ON tb_sync_operations (resulting_loan_id);
