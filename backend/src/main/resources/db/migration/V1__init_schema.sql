    reference_date  DATE,
    reference_key   VARCHAR(60),
    sent_at         TIMESTAMP(6),
    resolved_by     VARCHAR(50),
    resolved_at     TIMESTAMP(6),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6),
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES tb_beneficiaries (id),
    CONSTRAINT fk_notifications_loan FOREIGN KEY (loan_id) REFERENCES tb_loans (id),
    CONSTRAINT ck_notifications_recipient CHECK (recipient_type IN ('BENEFICIARIO', 'ADMINISTRADOR')),
    CONSTRAINT ck_notifications_channel CHECK (channel IS NULL OR channel IN ('WHATSAPP', 'SMS', 'EMAIL')),
    CONSTRAINT ck_notifications_type CHECK (type IN ('LEMBRETE_7_DIAS', 'LEMBRETE_1_DIA', 'VENCIMENTO_HOJE', 'ATRASO',
        'RESERVA_DISPONIVEL', 'INADIMPLENCIA', 'RESUMO_DIARIO', 'CONTATO_MANUAL', 'PREVENTIVA_VENCIDA', 'GERAL')),
    CONSTRAINT ck_notifications_status CHECK (status IN ('PENDENTE', 'ENVIADA', 'FALHA', 'AGUARDANDO_CONTATO_MANUAL',
        'CONCLUIDA_MANUALMENTE')),
    CONSTRAINT ck_notifications_attempts CHECK (attempts >= 0)
);
COMMENT ON TABLE tb_notifications IS 'Avisos e tarefas de contato manual (RN46–RN49). reference_date/reference_key deduplicam a régua.';
CREATE INDEX idx_notification_status ON tb_notifications (status);
CREATE INDEX idx_notification_dedupe ON tb_notifications (loan_id, type, reference_date);

-- ---------------------------------------------------------------------------------------------------------------------
-- Auditoria, parâmetros e ajuda (RF10, RF13, RF14)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_name  VARCHAR(60)  NOT NULL,
    entity_id    VARCHAR(100),
    action       VARCHAR(20)  NOT NULL,
    username     VARCHAR(50)  NOT NULL,
    automatic    BOOLEAN      NOT NULL DEFAULT FALSE,
    origin_rule  VARCHAR(30),
    details      TEXT,
    occurred_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_audit_logs PRIMARY KEY (id),
    CONSTRAINT ck_audit_logs_action CHECK (action IN ('CREATE', 'UPDATE', 'INACTIVATE', 'REACTIVATE', 'STATUS_CHANGE',
        'CANCEL', 'ANONYMIZE', 'ADJUSTMENT', 'LOGIN', 'LOGOUT', 'EXPORT'))
);
COMMENT ON TABLE tb_audit_logs IS 'Trilha de auditoria somente inserção (RN25, RN44, RN52, RN58). details = JSON {campo: {old, new}} ou filtros.';
CREATE INDEX idx_audit_entity ON tb_audit_logs (entity_name, entity_id);
CREATE INDEX idx_audit_occurred_at ON tb_audit_logs (occurred_at);

CREATE TABLE tb_system_parameters (
    param_key    VARCHAR(100) NOT NULL,
    param_value  VARCHAR(500) NOT NULL,
    description  VARCHAR(500),
    updated_by   VARCHAR(50),
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_system_parameters PRIMARY KEY (param_key)
);
COMMENT ON TABLE tb_system_parameters IS 'Parâmetros alterados pelo Admin; chave ausente = default do código (ParameterService).';

CREATE TABLE tb_help_contents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type           VARCHAR(20)  NOT NULL,
    title          VARCHAR(200) NOT NULL,
    content        TEXT         NOT NULL,
    keywords       VARCHAR(500),
    display_order  INTEGER      NOT NULL DEFAULT 0,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6),
    CONSTRAINT pk_help_contents PRIMARY KEY (id),
    CONSTRAINT ck_help_contents_type CHECK (type IN ('TUTORIAL', 'DICA', 'FAQ', 'ONBOARDING'))
);
COMMENT ON TABLE tb_help_contents IS 'Tutoriais, dicas, FAQ e onboarding mantidos pelo Admin (RN53).';
CREATE INDEX idx_help_content_active ON tb_help_contents (active);

CREATE TABLE tb_help_content_audiences (
    help_content_id  BIGINT      NOT NULL,
    audience         VARCHAR(20) NOT NULL,
    CONSTRAINT pk_help_content_audiences PRIMARY KEY (help_content_id, audience),
    CONSTRAINT fk_help_content_audiences_content FOREIGN KEY (help_content_id)
        REFERENCES tb_help_contents (id) ON DELETE CASCADE,
    CONSTRAINT ck_help_content_audiences_audience CHECK (audience IN ('PUBLICO', 'ADMIN', 'OPERADOR', 'CONSULTA'))
);

-- ---------------------------------------------------------------------------------------------------------------------
-- Dados institucionais do clube (fora da planilha; mantidos como estavam)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_lions_clubs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name             VARCHAR(120) NOT NULL,
    club_number      VARCHAR(30),
    district         VARCHAR(20)  NOT NULL,
    region           VARCHAR(50),
    city             VARCHAR(80),
    state            VARCHAR(2),
    zip_code         VARCHAR(10),
    foundation_date  DATE,
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6),
    CONSTRAINT pk_lions_clubs PRIMARY KEY (id),
    CONSTRAINT ck_lions_clubs_status CHECK (status IN ('ATIVO', 'INATIVO', 'SUSPENSO'))
);

CREATE TABLE tb_members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    club_id         BIGINT       NOT NULL,
    name            VARCHAR(120) NOT NULL,
    cpf             VARCHAR(14),
    email           VARCHAR(100) NOT NULL,
    phone           VARCHAR(20),
    role            VARCHAR(30)  NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    admission_date  DATE,
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6),
    CONSTRAINT pk_members PRIMARY KEY (id),
    CONSTRAINT uk_members_cpf UNIQUE (cpf),
    CONSTRAINT uk_members_email UNIQUE (email),
    CONSTRAINT fk_members_club FOREIGN KEY (club_id) REFERENCES tb_lions_clubs (id),
    CONSTRAINT ck_members_role CHECK (role IN ('PRESIDENTE', 'VICE_PRESIDENTE', 'SECRETARIO', 'TESOUREIRO',
        'DIRETOR_SOCIAL', 'DIRETOR_DE_ASSOCIADOS', 'ASSOCIADO')),
    CONSTRAINT ck_members_status CHECK (status IN ('ATIVO', 'INATIVO', 'SUSPENSO'))
);

CREATE TABLE tb_social_actions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    club_id          BIGINT       NOT NULL,
    title            VARCHAR(150) NOT NULL,
    description      TEXT,
    cause            VARCHAR(40)  NOT NULL,
    start_date       DATE,
    end_date         DATE,
    people_impacted  INTEGER,
    volunteer_hours  DOUBLE PRECISION,
    status           VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6),
    CONSTRAINT pk_social_actions PRIMARY KEY (id),
    CONSTRAINT fk_social_actions_club FOREIGN KEY (club_id) REFERENCES tb_lions_clubs (id),
    CONSTRAINT ck_social_actions_cause CHECK (cause IN ('ALIVIO_A_FOME', 'VISAO', 'DIABETES', 'CANCER_INFANTIL',
        'MEIO_AMBIENTE', 'SOCORRO_EM_CATASTROFES', 'DESENVOLVIMENTO_COMUNITARIO')),
    CONSTRAINT ck_social_actions_status CHECK (status IN ('ATIVO', 'INATIVO', 'SUSPENSO'))
);

