-- =====================================================================================================================
-- OrtoEmpresta (Lions Clube de Medianeira) — schema inicial · PostgreSQL 14+
-- Spec 001 (docs/specs/001-alinhamento-planilha). Nomes físicos em inglês; o MER lógico (docs/banco-de-dados/MER.json)
-- usa nomes em português — o mapeamento está no plan.md §3.1.
--
-- Executado pelo Flyway no perfil prod (spring.flyway.enabled=true, ddl-auto=validate). Em dev/teste o H2 continua
-- com o schema gerado pelo Hibernate.
--
-- Convenções:
--   * ids BIGINT IDENTITY (o patrimônio PT-0001 é derivado do id do equipamento — RN09);
--   * enums gravados pelo nome (VARCHAR + CHECK com os valores aceitos);
--   * datas/horas sem fuso (TIMESTAMP), geradas pelo servidor de aplicação (RN25);
--   * nenhuma tabela de negócio prevê exclusão física (RN03, RN26, RN41): FKs sem ON DELETE CASCADE, exceto as
--     coleções dependentes (canais, audiências, especificações).
-- =====================================================================================================================

-- ---------------------------------------------------------------------------------------------------------------------
-- Acesso (RF01)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username        VARCHAR(50)  NOT NULL,
    full_name       VARCHAR(120),
    email           VARCHAR(100) NOT NULL,
    password        VARCHAR(255) NOT NULL,
    role            VARCHAR(20)  NOT NULL,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at   TIMESTAMP(6),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ROLE_ADMIN', 'ROLE_OPERATOR', 'ROLE_VIEWER'))
);
COMMENT ON TABLE tb_users IS 'Usuários do sistema (MER: tb_usuario). Perfis fixos — RN01; exclusão só lógica — RN03.';

-- ---------------------------------------------------------------------------------------------------------------------
-- Beneficiários (RF02, RF09)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_addresses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cep             VARCHAR(9),
    street          VARCHAR(150),
    address_number  VARCHAR(20),
    complement      VARCHAR(100),
    neighborhood    VARCHAR(80),
    city            VARCHAR(80),
    state           VARCHAR(2),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6),
    CONSTRAINT pk_addresses PRIMARY KEY (id)
);
COMMENT ON TABLE tb_addresses IS 'Endereço do beneficiário, 1:1 (MER: tb_endereco). Número é texto para aceitar "S/N".';

CREATE TABLE tb_beneficiaries (
    id                                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    full_name                         VARCHAR(150) NOT NULL,
    cpf                               VARCHAR(11),
    birth_date                        DATE,
    phone                             VARCHAR(25),
    email                             VARCHAR(120),
    address_id                        BIGINT,
    alternative_contact_name          VARCHAR(150),
    alternative_contact_phone         VARCHAR(25),
    alternative_contact_relationship  VARCHAR(60),
    legally_incapable                 BOOLEAN      NOT NULL DEFAULT FALSE,
    legal_guardian_name               VARCHAR(150),
    legal_guardian_cpf                VARCHAR(11),
    legal_guardian_phone              VARCHAR(25),
    legal_guardian_email              VARCHAR(120),
    legal_guardian_relationship       VARCHAR(60),
    consent_granted                   BOOLEAN      NOT NULL DEFAULT FALSE,
    consent_timestamp                 TIMESTAMP(6),
    consent_given_by                  VARCHAR(150),
    active                            BOOLEAN      NOT NULL DEFAULT TRUE,
    inactivated_at                    TIMESTAMP(6),
    inactivation_reason               VARCHAR(500),
    anonymized                        BOOLEAN      NOT NULL DEFAULT FALSE,
    anonymized_at                     TIMESTAMP(6),
    notes                             TEXT,
    created_at                        TIMESTAMP(6) NOT NULL,
    updated_at                        TIMESTAMP(6),
    CONSTRAINT pk_beneficiaries PRIMARY KEY (id),
    CONSTRAINT uk_beneficiaries_address UNIQUE (address_id),
    CONSTRAINT fk_beneficiaries_address FOREIGN KEY (address_id) REFERENCES tb_addresses (id),
    CONSTRAINT ck_beneficiaries_cpf CHECK (cpf IS NULL OR cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_beneficiaries_guardian_cpf CHECK (legal_guardian_cpf IS NULL OR legal_guardian_cpf ~ '^[0-9]{11}$'),
    CONSTRAINT ck_beneficiaries_cpf_required CHECK (anonymized OR cpf IS NOT NULL),
    CONSTRAINT ck_beneficiaries_consent CHECK (NOT consent_granted OR consent_timestamp IS NOT NULL)
);
COMMENT ON TABLE tb_beneficiaries IS 'Beneficiários/assistidos (MER: tb_beneficiario). CPF só dígitos; nulo após anonimização (RN59).';
-- RN04: não pode haver dois cadastros ATIVOS com o mesmo CPF
CREATE UNIQUE INDEX ux_beneficiaries_cpf_active ON tb_beneficiaries (cpf) WHERE active AND cpf IS NOT NULL;
CREATE INDEX idx_beneficiary_cpf ON tb_beneficiaries (cpf);
CREATE INDEX idx_beneficiary_active ON tb_beneficiaries (active);

-- RN07/RN47: canais de notificação autorizados no consentimento
CREATE TABLE tb_beneficiary_channels (
    beneficiary_id  BIGINT      NOT NULL,
    channel         VARCHAR(20) NOT NULL,
    CONSTRAINT pk_beneficiary_channels PRIMARY KEY (beneficiary_id, channel),
    CONSTRAINT fk_beneficiary_channels_beneficiary FOREIGN KEY (beneficiary_id)
        REFERENCES tb_beneficiaries (id) ON DELETE CASCADE,
    CONSTRAINT ck_beneficiary_channels_channel CHECK (channel IN ('WHATSAPP', 'SMS', 'EMAIL'))
);

-- ---------------------------------------------------------------------------------------------------------------------
-- Equipamentos (RF03, RF04)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_equipment_types (
    code         VARCHAR(40) NOT NULL,
    description  VARCHAR(80) NOT NULL,
    loan_days    INTEGER,
    updated_by   VARCHAR(50),
    updated_at   TIMESTAMP(6),
    CONSTRAINT pk_equipment_types PRIMARY KEY (code),
    CONSTRAINT ck_equipment_types_code CHECK (code IN ('CADEIRA_DE_RODAS', 'CADEIRA_DE_BANHO', 'ANDADOR', 'MULETAS', 'OUTROS')),
    CONSTRAINT ck_equipment_types_loan_days CHECK (loan_days IS NULL OR loan_days > 0)
);
COMMENT ON TABLE tb_equipment_types IS 'Tipos de equipamento (MER: tb_equipamento_tipo) — RN14; prazo do empréstimo por tipo (RN18; NULL = loan.default-days).';

CREATE TABLE tb_equipments (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    patrimony_number               VARCHAR(40)  NOT NULL,
    type                           VARCHAR(40)  NOT NULL,
    equipment_size                 VARCHAR(50),
    manufacture_year               INTEGER,
    equipment_condition            VARCHAR(20)  NOT NULL,
    status                         VARCHAR(30)  NOT NULL,
    notes                          VARCHAR(500),
    photo_url                      VARCHAR(500),
    reserved_for_beneficiary_id    BIGINT,
    write_off_reason               VARCHAR(20),
    write_off_notes                VARCHAR(500),
    write_off_date                 DATE,
    write_off_by                   VARCHAR(50),
    last_maintenance_date          DATE,
    loan_cycles_since_maintenance  INTEGER      NOT NULL DEFAULT 0,
    version                        BIGINT,
    created_at                     TIMESTAMP(6) NOT NULL,
    updated_at                     TIMESTAMP(6),
    CONSTRAINT pk_equipments PRIMARY KEY (id),
    CONSTRAINT uk_equipments_patrimony UNIQUE (patrimony_number),
    CONSTRAINT fk_equipments_type FOREIGN KEY (type) REFERENCES tb_equipment_types (code),
    CONSTRAINT fk_equipments_reserved_for FOREIGN KEY (reserved_for_beneficiary_id) REFERENCES tb_beneficiaries (id),
    CONSTRAINT ck_equipments_condition CHECK (equipment_condition IN ('BOM', 'REGULAR', 'RUIM')),
    CONSTRAINT ck_equipments_status CHECK (status IN ('DISPONIVEL', 'RESERVADO', 'EMPRESTADO', 'EM_MANUTENCAO', 'BAIXADO')),
    CONSTRAINT ck_equipments_write_off_reason CHECK (write_off_reason IS NULL
        OR write_off_reason IN ('INSERVIVEL', 'PERDA', 'FURTO', 'DOACAO')),
    CONSTRAINT ck_equipments_write_off CHECK (status <> 'BAIXADO' OR write_off_reason IS NOT NULL),
    CONSTRAINT ck_equipments_year CHECK (manufacture_year IS NULL OR manufacture_year >= 1900),
    CONSTRAINT ck_equipments_cycles CHECK (loan_cycles_since_maintenance >= 0)
);
COMMENT ON TABLE tb_equipments IS 'Acervo (MER: tb_equipamento). Patrimônio PT-%04d imutável (RN09); status exclusivo (RN11/RN12); baixa = exclusão lógica (RN13).';
CREATE INDEX idx_equipment_status ON tb_equipments (status);
CREATE INDEX idx_equipment_type ON tb_equipments (type);
CREATE INDEX idx_equipment_type_status ON tb_equipments (type, status);

CREATE TABLE tb_equipment_specifications (
    equipment_id  BIGINT       NOT NULL,
    position      INTEGER      NOT NULL,
    name          VARCHAR(80)  NOT NULL,
    spec_value    VARCHAR(255) NOT NULL,
    CONSTRAINT pk_equipment_specifications PRIMARY KEY (equipment_id, position),
    CONSTRAINT fk_equipment_specifications_equipment FOREIGN KEY (equipment_id)
        REFERENCES tb_equipments (id) ON DELETE CASCADE
);
COMMENT ON TABLE tb_equipment_specifications IS 'Especificações nome/valor do equipamento (MER: tb_especificacao).';

-- ---------------------------------------------------------------------------------------------------------------------
-- Solicitações, empréstimos, termo, renovações e devoluções (RF05, RF07, RF10)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_loan_orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    beneficiary_id          BIGINT       NOT NULL,
    for_self                BOOLEAN      NOT NULL DEFAULT TRUE,
    requester_name          VARCHAR(150),
    requester_relationship  VARCHAR(60),
    equipment_type          VARCHAR(40)  NOT NULL,
    need_reason             TEXT,
    status                  VARCHAR(30)  NOT NULL,
    rejection_reason        VARCHAR(500),
    assisted_registration   BOOLEAN      NOT NULL DEFAULT FALSE,
    decided_by              VARCHAR(50),
    decided_at              TIMESTAMP(6),
    created_at              TIMESTAMP(6) NOT NULL,
    updated_at              TIMESTAMP(6),
    CONSTRAINT pk_loan_orders PRIMARY KEY (id),
    CONSTRAINT fk_loan_orders_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES tb_beneficiaries (id),
    CONSTRAINT fk_loan_orders_type FOREIGN KEY (equipment_type) REFERENCES tb_equipment_types (code),
    CONSTRAINT ck_loan_orders_status CHECK (status IN ('PENDENTE_ANALISE', 'APROVADO', 'REJEITADO', 'EM_FILA_ESPERA', 'CANCELADO'))
);
COMMENT ON TABLE tb_loan_orders IS 'Solicitações de empréstimo (pedido público/assistido). need_reason é dado sensível de saúde (LGPD).';
COMMENT ON COLUMN tb_loan_orders.need_reason IS 'Dado pessoal sensível (LGPD art. 5º, II) — limpo na anonimização (RN59).';
CREATE INDEX idx_loan_order_status ON tb_loan_orders (status);
CREATE INDEX idx_loan_order_beneficiary ON tb_loan_orders (beneficiary_id);

CREATE TABLE tb_loans (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    beneficiary_id                BIGINT       NOT NULL,
    equipment_id                  BIGINT       NOT NULL,
    order_id                      BIGINT,
    status                        VARCHAR(30)  NOT NULL,
    loan_date                     DATE         NOT NULL,
    initial_expected_return_date  DATE         NOT NULL,
    expected_return_date          DATE         NOT NULL,
    renewal_count                 INTEGER      NOT NULL DEFAULT 0,
    last_renewal_date             DATE,
    retroactive                   BOOLEAN      NOT NULL DEFAULT FALSE,
    retroactive_justification     VARCHAR(500),
    initial_condition             VARCHAR(20),
    delivery_notes                VARCHAR(500),
    delivery_photo_url            VARCHAR(500),
    term_pdf_path                 VARCHAR(300),
    term_hash_sha256              VARCHAR(64),
    term_generated_at             TIMESTAMP(6),
    signature_type                VARCHAR(30),
    signed_at                     TIMESTAMP(6),
    signed_by_name                VARCHAR(150),
    signed_document_path          VARCHAR(300),
    signature_registered_by       VARCHAR(50),
    created_by                    VARCHAR(50),
    returned_at                   TIMESTAMP(6),
    cancel_reason                 VARCHAR(500),
    canceled_by                   VARCHAR(50),
    canceled_at                   TIMESTAMP(6),
    created_at                    TIMESTAMP(6) NOT NULL,
    updated_at                    TIMESTAMP(6),
    CONSTRAINT pk_loans PRIMARY KEY (id),
    CONSTRAINT fk_loans_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES tb_beneficiaries (id),
    CONSTRAINT fk_loans_equipment FOREIGN KEY (equipment_id) REFERENCES tb_equipments (id),
    CONSTRAINT fk_loans_order FOREIGN KEY (order_id) REFERENCES tb_loan_orders (id),
    CONSTRAINT ck_loans_status CHECK (status IN ('PENDENTE_ASSINATURA', 'ATIVO', 'ATRASADO', 'DEVOLVIDO', 'CANCELADO')),
    CONSTRAINT ck_loans_initial_condition CHECK (initial_condition IS NULL OR initial_condition IN ('BOM', 'REGULAR', 'RUIM')),
    CONSTRAINT ck_loans_signature_type CHECK (signature_type IS NULL OR signature_type IN ('FISICA_DIGITALIZADA', 'DIGITAL')),
    CONSTRAINT ck_loans_dates CHECK (expected_return_date > loan_date AND initial_expected_return_date > loan_date),
    CONSTRAINT ck_loans_renewals CHECK (renewal_count >= 0),
    CONSTRAINT ck_loans_retroactive CHECK (NOT retroactive OR retroactive_justification IS NOT NULL),
    CONSTRAINT ck_loans_cancel CHECK (status <> 'CANCELADO' OR cancel_reason IS NOT NULL)
);
COMMENT ON TABLE tb_loans IS 'Empréstimos (MER: tb_emprestimo). Nunca excluídos — só cancelados (RN26). Termo PDF vinculado e não excluível (RN21, RN61).';
CREATE INDEX idx_loan_status ON tb_loans (status);
CREATE INDEX idx_loan_beneficiary ON tb_loans (beneficiary_id);
CREATE INDEX idx_loan_equipment ON tb_loans (equipment_id);
CREATE INDEX idx_loan_expected_return ON tb_loans (expected_return_date);
-- RN28: um equipamento só pode estar em um empréstimo em aberto
CREATE UNIQUE INDEX ux_loans_open_equipment ON tb_loans (equipment_id)
    WHERE status IN ('PENDENTE_ASSINATURA', 'ATIVO', 'ATRASADO');

CREATE TABLE tb_loan_renewals (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    loan_id            BIGINT       NOT NULL,
    previous_due_date  DATE         NOT NULL,
    new_due_date       DATE         NOT NULL,
    renewed_by         VARCHAR(50),
    renewed_at         TIMESTAMP(6) NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_loan_renewals PRIMARY KEY (id),
    CONSTRAINT fk_loan_renewals_loan FOREIGN KEY (loan_id) REFERENCES tb_loans (id),
    CONSTRAINT ck_loan_renewals_dates CHECK (new_due_date > previous_due_date)
);
COMMENT ON TABLE tb_loan_renewals IS 'Renovações, imutáveis (MER: tb_emprestimo_renovacao) — RN23, RN25.';
CREATE INDEX idx_loan_renewal_loan ON tb_loan_renewals (loan_id);

CREATE TABLE tb_loan_returns (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    loan_id             BIGINT       NOT NULL,
    return_date         DATE         NOT NULL,
    return_condition    VARCHAR(30)  NOT NULL,
    damage_description  VARCHAR(1000),
    return_photo_url    VARCHAR(500),
    has_damage          BOOLEAN      NOT NULL DEFAULT FALSE,
    received_by         VARCHAR(50),
    created_at          TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_loan_returns PRIMARY KEY (id),
    CONSTRAINT uk_loan_returns_loan UNIQUE (loan_id),
    CONSTRAINT fk_loan_returns_loan FOREIGN KEY (loan_id) REFERENCES tb_loans (id),
    CONSTRAINT ck_loan_returns_condition CHECK (return_condition IN ('BOM_ESTADO', 'PRECISA_MANUTENCAO', 'DANIFICADO'))
);
COMMENT ON TABLE tb_loan_returns IS 'Devolução com vistoria, imutável (MER: dt_devolucao/estado_devolucao de tb_emprestimo) — RN24, RN40.';
CREATE INDEX idx_loan_return_date ON tb_loan_returns (return_date);

CREATE TABLE tb_occurrences (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    beneficiary_id   BIGINT        NOT NULL,
    loan_id          BIGINT,
    type             VARCHAR(20)   NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    description      VARCHAR(1000) NOT NULL,
    automatic        BOOLEAN       NOT NULL DEFAULT FALSE,
    created_by       VARCHAR(50),
    resolved_at      TIMESTAMP(6),
    resolved_by      VARCHAR(50),
    resolution_note  VARCHAR(1000),
    created_at       TIMESTAMP(6)  NOT NULL,
    updated_at       TIMESTAMP(6),
    CONSTRAINT pk_occurrences PRIMARY KEY (id),
    CONSTRAINT fk_occurrences_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES tb_beneficiaries (id),
