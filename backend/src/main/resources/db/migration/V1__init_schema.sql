    CONSTRAINT ck_occurrences_status CHECK (status IN ('ABERTA', 'RESOLVIDA'))
);
COMMENT ON TABLE tb_occurrences IS 'Ocorrências de avaria (RN40) e inadimplência (RN27); abertas bloqueiam novas retiradas (RN20).';
CREATE INDEX idx_occurrence_beneficiary_status ON tb_occurrences (beneficiary_id, status);
CREATE INDEX idx_occurrence_loan ON tb_occurrences (loan_id);

-- ---------------------------------------------------------------------------------------------------------------------
-- Fila de espera (RF06)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_waitlist_entries (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    beneficiary_id           BIGINT       NOT NULL,
    equipment_type           VARCHAR(40)  NOT NULL,
    order_id                 BIGINT,
    status                   VARCHAR(20)  NOT NULL,
    queued_at                TIMESTAMP(6) NOT NULL,
    original_requested_at    TIMESTAMP(6) NOT NULL,
    priority                 BOOLEAN      NOT NULL DEFAULT FALSE,
    priority_reason          VARCHAR(30),
    priority_justification   VARCHAR(500),
    priority_authorized_by   VARCHAR(50),
    reserved_equipment_id    BIGINT,
    reserved_at              TIMESTAMP(6),
    reservation_expires_at   TIMESTAMP(6),
    consecutive_expirations  INTEGER      NOT NULL DEFAULT 0,
    removed_reason           VARCHAR(500),
    closed_at                TIMESTAMP(6),
    created_by               VARCHAR(50),
    created_at               TIMESTAMP(6) NOT NULL,
    updated_at               TIMESTAMP(6),
    CONSTRAINT pk_waitlist_entries PRIMARY KEY (id),
    CONSTRAINT fk_waitlist_beneficiary FOREIGN KEY (beneficiary_id) REFERENCES tb_beneficiaries (id),
    CONSTRAINT fk_waitlist_type FOREIGN KEY (equipment_type) REFERENCES tb_equipment_types (code),
    CONSTRAINT fk_waitlist_order FOREIGN KEY (order_id) REFERENCES tb_loan_orders (id),
    CONSTRAINT fk_waitlist_reserved_equipment FOREIGN KEY (reserved_equipment_id) REFERENCES tb_equipments (id),
    CONSTRAINT ck_waitlist_status CHECK (status IN ('AGUARDANDO', 'RESERVADO', 'ATENDIDO', 'REMOVIDO')),
    CONSTRAINT ck_waitlist_priority_reason CHECK (priority_reason IS NULL
        OR priority_reason IN ('URGENCIA_SAUDE', 'PESSOA_IDOSA', 'POS_OPERATORIO')),
    CONSTRAINT ck_waitlist_priority CHECK (NOT priority OR (priority_reason IS NOT NULL AND priority_justification IS NOT NULL)),
    CONSTRAINT ck_waitlist_expirations CHECK (consecutive_expirations >= 0)
);
COMMENT ON TABLE tb_waitlist_entries IS 'Fila por tipo de equipamento, FIFO com prioridade autorizada (MER: tb_fila_espera) — RN29–RN34.';
CREATE INDEX idx_waitlist_type_status ON tb_waitlist_entries (equipment_type, status);
CREATE INDEX idx_waitlist_beneficiary ON tb_waitlist_entries (beneficiary_id);
-- RN31: uma posição ativa por beneficiário e tipo
CREATE UNIQUE INDEX ux_waitlist_active_beneficiary_type ON tb_waitlist_entries (beneficiary_id, equipment_type)
    WHERE status IN ('AGUARDANDO', 'RESERVADO');

-- ---------------------------------------------------------------------------------------------------------------------
-- Manutenção (RF08)
-- ---------------------------------------------------------------------------------------------------------------------
CREATE TABLE tb_maintenances (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    equipment_id           BIGINT        NOT NULL,
    type                   VARCHAR(20)   NOT NULL,
    status                 VARCHAR(30)   NOT NULL,
    entry_date             DATE          NOT NULL,
    exit_date              DATE,
    defect_description     VARCHAR(1000) NOT NULL,
    technical_responsible  VARCHAR(150)  NOT NULL,
    verdict_notes          VARCHAR(1000),
    origin_loan_id         BIGINT,
    opened_by              VARCHAR(50),
    closed_by              VARCHAR(50),
    created_at             TIMESTAMP(6)  NOT NULL,
    updated_at             TIMESTAMP(6),
    CONSTRAINT pk_maintenances PRIMARY KEY (id),
    CONSTRAINT fk_maintenances_equipment FOREIGN KEY (equipment_id) REFERENCES tb_equipments (id),
    CONSTRAINT fk_maintenances_origin_loan FOREIGN KEY (origin_loan_id) REFERENCES tb_loans (id),
    CONSTRAINT ck_maintenances_type CHECK (type IN ('CORRETIVA', 'PREVENTIVA')),
    CONSTRAINT ck_maintenances_status CHECK (status IN ('EM_ANDAMENTO', 'CONCLUIDA_APTO', 'CONCLUIDA_INSERVIVEL')),
    CONSTRAINT ck_maintenances_dates CHECK (exit_date IS NULL OR exit_date >= entry_date)
);
COMMENT ON TABLE tb_maintenances IS 'Ordens de manutenção (MER: tb_manutencao) — RN35–RN39, RN41.';
CREATE INDEX idx_maintenance_equipment ON tb_maintenances (equipment_id);
CREATE INDEX idx_maintenance_status ON tb_maintenances (status);
-- RN35/RN36: no máximo uma manutenção em andamento por equipamento
CREATE UNIQUE INDEX ux_maintenances_open_equipment ON tb_maintenances (equipment_id) WHERE status = 'EM_ANDAMENTO';

CREATE TABLE tb_maintenance_costs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    maintenance_id     BIGINT        NOT NULL,
    type               VARCHAR(20)   NOT NULL,
    description        VARCHAR(500)  NOT NULL,
    part_replaced      VARCHAR(150),
    amount             NUMERIC(12, 2) NOT NULL,
    adjustment         BOOLEAN       NOT NULL DEFAULT FALSE,
    adjustment_reason  VARCHAR(500),
    registered_by      VARCHAR(50),
    registered_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT pk_maintenance_costs PRIMARY KEY (id),
    CONSTRAINT fk_maintenance_costs_maintenance FOREIGN KEY (maintenance_id) REFERENCES tb_maintenances (id),
    CONSTRAINT ck_maintenance_costs_type CHECK (type IN ('PECA', 'SERVICO')),
    CONSTRAINT ck_maintenance_costs_amount CHECK (adjustment OR amount >= 0),
    CONSTRAINT ck_maintenance_costs_adjustment CHECK (NOT adjustment OR adjustment_reason IS NOT NULL)
);
COMMENT ON TABLE tb_maintenance_costs IS 'Custos (peças/serviços) por manutenção; ajustes podem ser negativos (RN38, RN41).';
CREATE INDEX idx_maintenance_cost_maintenance ON tb_maintenance_costs (maintenance_id);

